function Files = export_comparison_table(Results,out_dir)
% =========================================================================
% export_comparison_table
%
% Write:
%   comparison_table.csv
%   batch_metrics.csv
%
% 加入了 Oh (文献12) 方法的对比数据
% Counts are channel-samples.
% Coverage entries are joint-vector coverage percentages.
% =========================================================================

    if exist(out_dir,'dir') ~= 7
        [ok,message] = mkdir(out_dir);

        if ~ok
            error('export_comparison_table: cannot create directory: %s', ...
                message);
        end
    end

    Prop = Results.Metrics_prop;
    Xue = Results.Metrics_xue;

    % 安全提取 Oh 指标
    if isfield(Results, 'Metrics_oh')
        Oh = Results.Metrics_oh;
    else
        Oh = struct();
    end

    % 安全提取 Oh 数据
    has_oh_data = isfield(Results, 'Data_oh') && ~isempty(Results.Data_oh);

    %% 1. Summary table
    % 构建汇总表行 (增加第4列 Oh 的数据)
    rows = { ...
        'Applied input violations', ...
            get_m(Prop,'input_applied_violations'), ...
            get_m(Xue,'input_applied_violations'), ...
            get_m(Oh,'input_applied_violations'); ...
        'Requested input violations', ...
            get_m(Prop,'input_request_violations'), ...
            get_m(Xue,'input_request_violations'), ...
            get_m(Oh,'input_request_violations'); ...
        'Input clipping channel-samples', ...
            get_m(Prop,'input_clips'), ...
            get_m(Xue,'input_clips'), ...
            get_m(Oh,'input_clips'); ...
        'Input boundary hits', ...
            get_m(Prop,'input_boundary_hits'), ...
            get_m(Xue,'input_boundary_hits'), ...
            get_m(Oh,'input_boundary_hits'); ...
        'Measured output violations', ...
            get_m(Prop,'output_measured_violations'), ...
            get_m(Xue,'output_measured_violations'), ...
            get_m(Oh,'output_measured_violations'); ...
        'Noise-free output violations', ...
            get_m(Prop,'output_true_violations'), ...
            get_m(Xue,'output_true_violations'), ...
            get_m(Oh,'output_true_violations'); ...
        'Maximum applied input violation', ...
            get_m(Prop,'max_input_applied_violation'), ...
            get_m(Xue,'max_input_applied_violation'), ...
            get_m(Oh,'max_input_applied_violation'); ...
        'Maximum requested input violation', ...
            get_m(Prop,'max_input_request_violation'), ...
            get_m(Xue,'max_input_request_violation'), ...
            get_m(Oh,'max_input_request_violation'); ...
        'Maximum measured output violation', ...
            get_m(Prop,'max_output_measured_violation'), ...
            get_m(Xue,'max_output_measured_violation'), ...
            get_m(Oh,'max_output_measured_violation'); ...
        'Maximum noise-free output violation', ...
            get_m(Prop,'max_output_true_violation'), ...
            get_m(Xue,'max_output_true_violation'), ...
            get_m(Oh,'max_output_true_violation'); ...
        'Final actual versus true target error', ...
            get_m(Prop,'final_actual_reference_error'), ...
            get_m(Xue,'final_actual_reference_error'), ...
            get_m(Oh,'final_actual_reference_error'); ...
        'Final actual versus optimal reachable error', ...
            get_m(Prop,'final_actual_optimal_error'), ...
            get_m(Xue,'final_actual_optimal_error'), ...
            get_m(Oh,'final_actual_optimal_error'); ...
        'Final nominal versus optimal reachable error', ...
            get_m(Prop,'final_nominal_optimal_error'), ...
            get_m(Xue,'final_nominal_optimal_error'), ...
            get_m(Oh,'final_nominal_optimal_error'); ...
        'Innovation box coverage percent', ...
            get_m(Prop,'eta_box_coverage')*100, ...
            get_m(Xue,'eta_box_coverage')*100, ...
            get_m(Oh,'eta_box_coverage')*100; ...
        'Reconstruction box coverage percent', ...
            get_m(Prop,'r_box_coverage')*100, ...
            get_m(Xue,'r_box_coverage')*100, ...
            get_m(Oh,'r_box_coverage')*100; ...
        'Innovation ellipsoid coverage percent', ...
            get_m(Prop,'eta_ellipsoid_coverage')*100, ...
            get_m(Xue,'eta_ellipsoid_coverage')*100, ...
            get_m(Oh,'eta_ellipsoid_coverage')*100; ...
        'Reconstruction ellipsoid coverage percent', ...
            get_m(Prop,'r_ellipsoid_coverage')*100, ...
            get_m(Xue,'r_ellipsoid_coverage')*100, ...
            get_m(Oh,'r_ellipsoid_coverage')*100; ...
        'Post-input error inside Tube percent diagnostic', ...
            get_m(Prop,'tube_post_coverage')*100, ...
            get_m(Xue,'tube_post_coverage')*100, ...
            get_m(Oh,'tube_post_coverage')*100; ...
        'Mean solver time seconds', ...
            get_m(Prop,'mean_solver_time'), ...
            get_m(Xue,'mean_solver_time'), ...
            get_m(Oh,'mean_solver_time'); ...
        'Maximum solver time seconds', ...
            get_m(Prop,'max_solver_time'), ...
            get_m(Xue,'max_solver_time'), ...
            get_m(Oh,'max_solver_time'); ...
        'Total simulation time seconds', ...
            get_m(Prop,'total_simulation_time'), ...
            get_m(Xue,'total_simulation_time'), ...
            get_m(Oh,'total_simulation_time') ...
    };

    summary_file = fullfile(out_dir,'comparison_table.csv');
    fid = fopen(summary_file,'w');

    if fid < 0
        error('export_comparison_table: cannot open %s.',summary_file);
    end

    cleanup_summary = onCleanup(@() fclose(fid));

    % 更新表头，增加 Oh 列
    fprintf(fid,'Metric,Tube,Xue adapted,Oh adapted\n');

    for j = 1:size(rows,1)
        fprintf(fid,'%s,%.12g,%.12g,%.12g\n', ...
            rows{j,1},rows{j,2},rows{j,3},rows{j,4});
    end

    clear cleanup_summary;

    %% 2. Per-batch table
    batch_file = fullfile(out_dir,'batch_metrics.csv');
    fid = fopen(batch_file,'w');

    if fid < 0
        error('export_comparison_table: cannot open %s.',batch_file);
    end

    cleanup_batch = onCleanup(@() fclose(fid));

    fprintf(fid,[ ...
        'Method,Batch,ActualTargetError,ActualOptimalError,' ...
        'NominalOptimalError,SolverTimeSeconds,' ...
        'ClippedChannelSamples,InnovationEllipsoidCoveragePercent,' ...
        'ReconstructionEllipsoidCoveragePercent,' ...
        'PostInputTubeCoveragePercent,MaximumTubeQuadratic\n' ...
    ]);

    % 将 Oh 数据加入 datasets
    datasets = {Results.Data_prop, Results.Data_xue};
    names = {'Tube', 'Xue adapted'};

    if has_oh_data
        datasets{end+1} = Results.Data_oh;
        names{end+1} = 'Oh adapted';
    end

    for method = 1:numel(datasets)
        Data = datasets{method};

        for b = 1:Results.Params.N_batches
            Batch = Data.Batch{b};

            fprintf(fid,[ ...
                '%s,%d,%.12g,%.12g,%.12g,%.12g,%d,' ...
                '%.12g,%.12g,%.12g,%.12g\n' ...
            ], ...
                names{method},b, ...
                Data.Err_true_act(b), ...
                Data.Err_opt_act(b), ...
                Data.Err_opt_nom(b), ...
                Data.QP_times(b), ...
                sum(Batch.clip_flags(:)), ...
                100*mean(Batch.eta_ellipsoid_in), ...
                100*mean(Batch.r_ellipsoid_in), ...
                100*mean(Batch.tube_post_quadratic <= 1+1e-7), ...
                max(Batch.tube_post_quadratic));
        end
    end

    clear cleanup_batch;

    Files = struct();
    Files.summary = summary_file;
    Files.per_batch = batch_file;

    fprintf('Saved: %s\n',summary_file);
    fprintf('Saved: %s\n',batch_file);
end

% =========================================================================
% 辅助函数：安全提取指标值，如果字段不存在则返回 NaN
% =========================================================================
function val = get_m(S, field)
    if isfield(S, field)
        val = S.(field);
    else
        val = NaN;
    end
end
